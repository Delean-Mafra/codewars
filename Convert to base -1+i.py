def base_i_min_one(dm):
    if dm == 0:
        return '0'
    dm1 = []
    while dm != 0:
        dm2 = int(dm.real)
        dm3 = int(dm.imag)
        dm4 = (dm2 - dm3) % 2
        dm1.append(str(dm4))
        dm5 = -((dm2 - dm4 - dm3) // 2)
        dm6 = -((dm2 - dm4 + dm3) // 2)
        dm = complex(dm5, dm6)
    return ''.join(reversed(dm1))

