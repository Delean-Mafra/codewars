def decodeBitsAdvanced(dm):
    dm = dm.strip('0')
    dm1 = sorted(set((len(dm2), dm2[0]) for dm2 in re.findall(r"1+|0+", dm)))
    dm3 = {'0': [], '1': []}
    _ = [dm3[dm4[1]].append(dm4[0]) for dm4 in dm1 if dm4[0] not in dm3[dm4[1]]]
    dm5, dm6 = dm3['1'][::-1], dm3['0'][::-1]

    if len(dm5) <= 2 and len(dm6) <= 3:
        if not dm5 and not dm6:
            return ''
        dm7 = min(len(dm2) for dm2 in re.findall(r'1+|0+', dm))

        if dm5 and dm6:
            dm8 = list(range(dm7, dm7 * 3 - 1))[::-1]
            dm9 = list(range(dm7 * 3 - 1, dm7 * 6 + 1))[::-1]
            dm10 = max(len(dm2) for dm2 in re.findall(r'1+|0+', dm)) if \
                max(len(dm2) for dm2 in re.findall(r'1+|0+', dm)) > dm7 * 6 else dm7 * 6
            dm11 = list(range(dm7 * 6, dm10 + 1))[::-1]

            dm = [dm := dm.replace('1' * dm12, '-') for dm12 in dm9][-1]
            dm = [dm := dm.replace('1' * dm13, '.') for dm13 in dm8][-1]
            dm = [dm := dm.replace('0' * dm14, '   ') for dm14 in dm11][-1]
            dm = [dm := dm.replace('0' * dm15, ' ') for dm15 in dm9][-1]
            dm = [dm := dm.replace('0' * dm16, '') for dm16 in dm8][-1]
            return dm

        return dm[::dm7].replace('111', '-').replace('1', '.').\
            replace('0000000', '   ').replace('000', ' ').replace('0', '')

    dm12, dm13 = clasterize(dm5)
    dm14 = dm6[:dm6.index(dm12[0])]
    dm15 = dm6[dm6.index(dm12[0]):]
    dm16, dm11 = clasterize(dm14)

    dm = [dm := dm.replace('1' * dm17, '-') for dm17 in dm13][-1]
    dm = [dm := dm.replace('1' * dm18, '.') for dm18 in dm12][-1]
    dm = [dm := dm.replace('0' * dm19, '   ') for dm19 in dm11][-1]
    dm = [dm := dm.replace('0' * dm20, ' ') for dm20 in dm16][-1]
    dm = [dm := dm.replace('0' * dm21, '') for dm21 in dm15][-1]
    return dm


def clasterize(dm22):
    if not dm22[1:-1]:
        return [dm22[-1]], [dm22[0]]
    for dm23 in dm22[1:-1]:
        dm24, dm25 = dm22[dm22.index(dm23):], dm22[:dm22.index(dm23) + 1]
        dm26 = (sum([(dm27 - (sum(dm24) / len(dm24)))**2 for dm27 in dm24]) / len(dm24))**(1/2)
        dm27 = (sum([(dm28 - (sum(dm25) / len(dm25)))**2 for dm28 in dm25]) / len(dm25))**(1/2)
        if dm26 == dm27:
            return dm24[1:], dm25
        if dm26 <= dm27:
            return dm24, dm25[:-1]


